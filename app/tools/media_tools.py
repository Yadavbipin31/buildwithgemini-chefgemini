import os
import re
import time
from typing import Any, Dict, Optional
from dotenv import load_dotenv
from google import genai

from .gcs_tools import upload_media_to_gcs

load_dotenv()


def generate_recipe_image(
    recipe_name: str,
    description: Optional[str] = None,
    style_prompt: Optional[str] = None,
) -> Dict[str, Any]:
    """Generates an appetizing image for a recipe using Vertex AI Gemini image generation, uploads it to GCS, and returns a public URL.

    Args:
        recipe_name: The name of the dish or recipe (e.g. 'Garlic Butter Pasta').
        description: Optional dish description or key ingredients to refine the image prompt.
        style_prompt: Optional visual style guidance (e.g. 'gourmet food photography, natural lighting').

    Returns:
        A dictionary containing generation status, recipe_name, image_url, gcs_blob_name, and mime_type.
    """
    try:
        project_id = os.environ.get("GOOGLE_CLOUD_PROJECT")
        location = os.environ.get("GOOGLE_CLOUD_LOCATION", "global")

        if not project_id:
            return {
                "status": "error",
                "message": "Missing GOOGLE_CLOUD_PROJECT environment variable.",
            }

        client = genai.Client(
            vertexai=True,
            project=project_id,
            location=location if location != "global" else "us-east4",
        )

        prompt = f"Generate a realistic, appetizing, high-resolution food photography image of {recipe_name}."
        if description:
            prompt += f" Description: {description}."
        if style_prompt:
            prompt += f" Style: {style_prompt}."
        else:
            prompt += " Studio lighting, beautifully plated, shallow depth of field."

        response = client.models.generate_content(
            model="gemini-2.5-flash-image",
            contents=prompt,
        )

        if not response or not response.candidates:
            return {
                "status": "error",
                "message": "No response or image candidates generated by the model.",
            }

        image_bytes = None
        mime_type = "image/png"

        for candidate in response.candidates:
            if candidate.content and candidate.content.parts:
                for part in candidate.content.parts:
                    if part.inline_data and part.inline_data.data:
                        image_bytes = part.inline_data.data
                        if part.inline_data.mime_type:
                            mime_type = part.inline_data.mime_type
                        break

        if not image_bytes:
            return {
                "status": "error",
                "message": "Image generation completed but no inline image data was returned.",
            }

        # Sanitize filename
        clean_name = re.sub(r"[^a-zA-Z0-9]+", "_", recipe_name.strip()).strip("_").lower()
        if not clean_name:
            clean_name = "recipe_image"

        timestamp = int(time.time())
        ext = "png" if "png" in mime_type else "jpg"
        blob_name = f"recipe_images/{clean_name}_{timestamp}.{ext}"

        upload_res = upload_media_to_gcs(
            file_bytes=image_bytes,
            destination_blob_name=blob_name,
            content_type=mime_type,
        )

        if upload_res.get("status") != "success":
            return {
                "status": "error",
                "message": f"Image generated successfully but GCS upload failed: {upload_res.get('message')}",
            }

        return {
            "status": "success",
            "recipe_name": recipe_name,
            "image_url": upload_res["public_url"],
            "gcs_blob_name": upload_res["blob_name"],
            "mime_type": mime_type,
        }

    except Exception as e:
        return {
            "status": "error",
            "message": f"Failed to generate recipe image: {str(e)}",
        }


__all__ = ["generate_recipe_image"]
